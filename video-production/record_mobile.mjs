import {createRequire} from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const {chromium}=createRequire(path.join(root,'../frontend/package.json'))('@playwright/test');
const state=JSON.parse(fs.readFileSync(`${root}/runtime/recording-state.json`,'utf8'));
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,recordVideo:{dir:`${root}/recordings/raw`,size:{width:390,height:844}}});
const page=await context.newPage();const start=Date.now();const checks=[];
page.on('response',r=>{if(r.url().includes('/api/'))checks.push({url:r.url(),status:r.status()});});
await page.goto(state.share.url);await page.waitForLoadState('networkidle');await page.waitForTimeout(3000);
await page.screenshot({path:`${root}/reports/mobile-browser.png`});
await page.getByRole('button',{name:'下一张本体照片'}).click();await page.waitForTimeout(1800);
await page.mouse.wheel(0,480);await page.waitForTimeout(3000);await page.mouse.wheel(0,460);await page.waitForTimeout(3000);await page.mouse.wheel(0,-940);await page.waitForTimeout(3000);
await page.close();const video=await page.video().path();await context.close();await browser.close();
fs.writeFileSync(`${root}/reports/capture-mobile-raw.json`,JSON.stringify({stage:'mobile',video,duration:(Date.now()-start)/1000,emulatedViewport:true,physicalPhoneRecording:false,checks},null,2));console.log('Mobile browser capture complete:',video);
